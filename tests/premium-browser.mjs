import assert from "node:assert/strict";
import { readFileSync, mkdirSync, writeFileSync } from "node:fs";
import { pathToFileURL } from "node:url";
import { Pool } from "pg";
import { validateImageIsolatedEnvironment } from "./image-isolated.mjs";

validateImageIsolatedEnvironment(process.env);
const base = process.env.TEST_BASE_URL ?? "http://127.0.0.1:3212";
assert.ok(/^http:\/\/127\.0\.0\.1:3212$/.test(base) || /^https:\/\/content-[a-z0-9-]+\.vercel\.app$/.test(base));
const { users: [alice, bob] } = JSON.parse(readFileSync(process.env.PREVIEW_ACCOUNTS_FILE, "utf8"));
const { chromium } = await import(pathToFileURL(process.env.PLAYWRIGHT_MODULE).href);
const browser = await chromium.launch({ headless: true });
const headers = {};
if (base.startsWith("http://127.0.0.1:")) headers["x-vercel-forwarded-for"] = `198.18.${Math.floor(Math.random() * 255)}.12`;
if (process.env.VERCEL_OIDC_TOKEN) headers["x-vercel-trusted-oidc-idp-token"] = process.env.VERCEL_OIDC_TOKEN;
const context = await browser.newContext({ viewport: { width: 1440, height: 1000 }, acceptDownloads: true });
if (Object.keys(headers).length) await context.route(base + "/**", route => route.continue({ headers: { ...route.request().headers(), ...headers } }));
const page = await context.newPage(), errors = [], checks = [];
page.on("pageerror", e => errors.push(e.message));
page.on("console", m => { if (m.type() === "error" && !/502|409/.test(m.text())) errors.push(m.text()); });
const output = process.env.TEST_ARTIFACT_DIR ?? "/tmp/contentos-premium-browser";
mkdirSync(output, { recursive: true });
const pool = new Pool({ connectionString: process.env.DATABASE_URL, max: 1 });
async function count() {
  const { rows } = await pool.query("SELECT data FROM contentos_app.profiles WHERE id=$1 AND email=$2 AND data->>'premium_preview_fixture'='true'", [alice.id, alice.email]);
  assert.equal(rows.length, 1);
  const events = rows[0].data.usage_events_json ?? [];
  return { usage: events.filter(e => e.event_type === "text_generation").length, history: (rows[0].data.generation_history_json ?? []).length };
}
async function login(p, user) {
  await p.goto(base + "/login");
  await p.getByLabel("Email", { exact: true }).fill(user.email);
  await p.getByLabel("Password", { exact: true }).fill(user.password);
  await p.getByRole("button", { name: "Log in", exact: true }).click();
  await p.waitForURL("**/dashboard");
  await p.goto(base + "/studio");
  await p.getByRole("button", { name: "Generate content pack", exact: true }).waitFor();
}
let stage = "login";
try {
  await login(page, alice);
  assert.doesNotMatch(await page.locator('meta[name="viewport"]').getAttribute("content"), /maximum-scale|user-scalable=no/);
  const source = page.getByLabel("What would you like to create?");
  await source.fill("A synthetic stationery brand offers reusable planning notebooks. No claims about measured results. No CTA.");
  for (const checkbox of await page.locator("fieldset input[type=checkbox]").all()) await checkbox.check();
  const before = await count();
  stage = "real generation route with server fixture";
  const generated = page.waitForResponse(r => r.url() === base + "/api/generate" && r.request().method() === "POST");
  await page.getByRole("button", { name: "Generate content pack", exact: true }).click();
  const response = await generated;
  assert.equal(response.status(), 200);
  const pack = await response.json(), request = response.request().postDataJSON();
  assert.equal(pack.sections.length, 14);
  await page.getByRole("heading", { name: "Preview content pack", exact: true }).first().waitFor();
  assert.equal(await page.locator("#outputs article").count(), 14);
  const repeated = await context.request.post(base + "/api/generate", { headers: { ...headers, origin: base, "X-ContentOS-Account": alice.id }, data: request });
  assert.equal(repeated.status(), 200); assert.equal((await repeated.json()).id, pack.id);
  assert.deepEqual(await count(), { usage: before.usage + 1, history: before.history + 1 });
  checks.push("14 formats through actual route and isolated database; replay is exactly once");
  stage = "edit undo and refinement";
  const card = page.locator("#outputs article").first();
  await card.getByRole("button", { name: "Edit", exact: true }).click();
  await card.getByLabel(/Edit .* body/).fill("A manually edited synthetic draft.");
  await card.getByRole("button", { name: "Apply edits" }).click();
  await card.getByText("Manually edited", { exact: true }).waitFor();
  await page.getByRole("button", { name: "Undo edit", exact: true }).click();
  assert.equal(await card.getByText("Manually edited", { exact: true }).count(), 0);
  await card.getByRole("button", { name: "Refine with AI", exact: true }).click();
  await card.getByText("AI refined", { exact: true }).waitFor();
  assert.deepEqual(await count(), { usage: before.usage + 2, history: before.history + 2 });
  const download = page.waitForEvent("download");
  await page.getByRole("button", { name: "Download .txt", exact: true }).click();
  assert.match((await download).suggestedFilename(), /\.txt$/);
  await page.getByRole("button", { name: "Save all", exact: true }).click();
  await page.waitForTimeout(1600);
  checks.push("manual edits, undo, refinement provenance, save and text export");
  stage = "failed generation preserves draft and content";
  const editedBody = await card.innerText();
  await page.route(base + "/api/generate", route => route.fulfill({ status: 502, json: { error: "Synthetic provider failure. Your existing draft is unchanged.", code: "invalid_generation" } }), { times: 1 });
  await page.getByRole("button", { name: "Regenerate current set", exact: true }).click();
  await page.getByRole("alert").filter({ hasText: "Synthetic provider failure" }).waitFor();
  assert.equal(await card.innerText(), editedBody);
  assert.equal(await source.inputValue(), request.source);
  assert.deepEqual(await count(), { usage: before.usage + 2, history: before.history + 2 });
  checks.push("injected provider failure retains content and draft without a successful-usage charge");
  stage = "image fallback";
  await card.getByRole("button", { name: "Generate Image", exact: true }).click();
  await page.getByRole("button", { name: "Generate visual", exact: true }).click();
  const image = page.getByAltText(/Generated visual for/).last();
  await image.waitFor();
  await image.evaluate(img => img.decode());
  assert.ok(await image.evaluate(img => img.naturalWidth > 0));
  await page.getByText("No image credit was used.", { exact: false }).last().waitFor();
  await page.keyboard.press("Escape");
  checks.push("real template image render and no image-credit charge; no provider configured");
  stage = "responsive and cloud recovery";
  for (const width of [1440, 768, 390]) {
    await page.setViewportSize({ width, height: 900 });
    await page.screenshot({ path: output + `/studio-${width}.png` });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
  }
  const snapshot = await context.request.get(base + "/api/workspace", { headers: { ...headers, "X-ContentOS-Account": alice.id } });
  assert.equal(snapshot.status(), 200);
  const saved = await snapshot.json();
  assert.ok(saved.store.recent.some(p => p.id === pack.id && p.sections.some(s => s.revisionSource === "refined")));
  await page.reload();
  await page.getByRole("button", { name: "Generate content pack", exact: true }).waitFor();
  assert.equal(await source.inputValue(), request.source);
  checks.push("desktop/tablet/mobile without overflow; cloud retains edits and reload recovers draft");
  stage = "second device and account isolation";
  const second = await browser.newContext({ viewport: { width: 768, height: 1024 } });
  if (Object.keys(headers).length) await second.route(base + "/**", route => route.continue({ headers: { ...route.request().headers(), ...headers } }));
  const device = await second.newPage();
  await login(device, alice);
  assert.equal(await device.getByLabel("What would you like to create?").inputValue(), request.source);
  await second.close();
  const switched = await context.request.post(base + "/api/auth/login", { headers: { ...headers, origin: base }, data: { email: bob.email, password: bob.password } });
  assert.equal(switched.status(), 200);
  const stale = await context.request.post(base + "/api/generate", { headers: { ...headers, origin: base, "X-ContentOS-Account": alice.id }, data: request });
  assert.equal(stale.status(), 409);
  const other = await context.request.get(base + "/api/workspace", { headers: { ...headers, "X-ContentOS-Account": bob.id } });
  assert.equal(other.status(), 200);
  assert.ok(!(await other.text()).includes(pack.id));
  checks.push("independent-device hydration; account switch rejects stale generation and isolates content");
  assert.deepEqual(errors, []);
  const report = { result: "PASS", checks, viewports: [1440, 768, 390], liveAiCalls: 0, errors, artifactDirectory: output };
  writeFileSync(output + "/report.json", JSON.stringify(report, null, 2));
  console.log(JSON.stringify(report, null, 2));
} catch (error) {
  await page.screenshot({ path: output + "/failure.png", fullPage: true }).catch(() => {});
  console.error(JSON.stringify({ result: "FAIL", stage, checks, errors, error: error.message }));
  throw error;
} finally { await browser.close(); await pool.end(); }
